import logging

from odoo import _, api, fields, models
from odoo.exceptions import UserError, ValidationError
from odoo.osv import expression

_logger = logging.getLogger(__name__)


class MailMessage(models.Model):
    _inherit = "mail.message"

    user_vote = fields.Integer(
        string="User Vote",
        default=0,
        help="Vote status given by the user. 0: No vote, 1: Upvoted, -1: Downvoted.",
    )

    @api.model
    def _message_fetch(
        self,
        domain,
        search_term=None,
        before=None,
        after=None,
        around=None,
        limit=30,
        *,
        thread=None,
        is_notification=None,
    ):
        """Override to filter only LLM messages for llm.thread model.

        Odoo 18's parent accepts domain, search_term, before, after, around and
        limit, including as positional arguments. ``thread`` and
        ``is_notification`` are the Odoo 19 keywords. They are accepted so a
        caller that still passes them does not crash, and they are not
        forwarded: Odoo 18 raises TypeError on either one. ``thread`` is used
        locally when the domain does not identify the model. ``is_notification``
        has no Odoo 18 equivalent and is ignored.

        For LLM threads, only messages with an llm_role are returned. Ordinary
        chatter is not given that filter.
        """
        # Odoo 18 does not filter on this flag. Keep the parameter so it is
        # not treated as an unexpected keyword, and do not forward it.
        del is_notification

        is_llm_thread = bool(thread) and thread._name == "llm.thread"
        if not is_llm_thread and domain:
            # The thread may only be identifiable through the domain itself.
            is_llm_thread = any(
                condition[0] == "model"
                and condition[1] == "="
                and condition[2] == "llm.thread"
                for condition in domain
                if isinstance(condition, (list, tuple)) and len(condition) == 3
            )

        if is_llm_thread:
            # Add LLM role filter for LLM threads - only show messages with llm_role
            domain = expression.AND([domain or [], [("llm_role", "!=", False)]])

        return super()._message_fetch(
            domain,
            search_term=search_term,
            before=before,
            after=after,
            around=around,
            limit=limit,
        )

    def _extras_to_store(self, store, format_reply):
        """Add LLM-specific fields to the message store."""
        super()._extras_to_store(store, format_reply)

        for message in self:
            data = {}

            # Add LLM-specific fields
            if hasattr(message, "llm_role") and message.llm_role:
                data["llm_role"] = message.llm_role
                # Set is_note=True for LLM messages to get the right bubble style
                data["is_note"] = True

            if hasattr(message, "user_vote"):
                data["user_vote"] = message.user_vote

            if hasattr(message, "body_json") and message.body_json:
                data["body_json"] = message.body_json

            if data:  # Only add to store if we have data
                store.add(message, data)

    def set_user_vote(self, vote_value):
        """Sets the user vote on this message, performing validation checks."""
        self.ensure_one()
        if self.llm_role not in ("assistant", "tool"):
            raise UserError(
                _(
                    "Voting is only allowed on messages generated by the assistant or a tool."
                )
            )
        if not isinstance(vote_value, int) or vote_value not in [-1, 0, 1]:
            raise ValidationError(
                _(
                    "Invalid vote value. Must be an integer: 1 (up), -1 (down), or 0 (none)."
                )
            )
        self.sudo().write({"user_vote": vote_value})
